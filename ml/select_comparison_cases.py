#!/usr/bin/env python3
"""Select the 20 RTL-vs-native-TFLM comparison cases (prompt Section 7):
five test-split samples per category, by a deterministic ID-based rule
(lowest sample_id within the test split), selected after the model was
frozen and without filtering by correctness or confidence. Quantizes each
selected sample's tensor using the chosen model's actual int8 input
scale/zero_point, and emits the raw bytes both as a manifest (for the
native reference and RTL-comparison checker) and as a C header for the
bare-metal firmware to embed as constants.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd
import tensorflow as tf

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
RESULTS = ROOT / "results"
SW_GEN = ROOT / "sw" / "generated"
SW_GEN.mkdir(parents=True, exist_ok=True)

CLASSES = ["Center", "Edge-Ring", "Scratch", "none"]
N_PER_CLASS = 5

ml_metrics = json.load(open(RESULTS / "ml_metrics.json"))
CHOSEN_TAG = ml_metrics["chosen_configuration"]
TFLITE_PATH = ROOT / "models" / f"model_{CHOSEN_TAG}_int8.tflite"


def main():
    manifest = pd.read_csv(PROCESSED / "selection_manifest.csv")
    data = np.load(PROCESSED / "tensors.npz", allow_pickle=True)
    X = data["X"]
    sample_ids = data["sample_id"]
    id_to_idx = {int(sid): i for i, sid in enumerate(sample_ids)}

    test_rows = manifest[manifest["split"] == "test"].sort_values("sample_id")

    chosen_rows = []
    for cls in CLASSES:
        cls_rows = test_rows[test_rows["class_name"] == cls].head(N_PER_CLASS)
        chosen_rows.append(cls_rows)
    chosen = pd.concat(chosen_rows).reset_index(drop=True)
    assert len(chosen) == len(CLASSES) * N_PER_CLASS, \
        f"expected {len(CLASSES) * N_PER_CLASS} cases, got {len(chosen)}"

    interp = tf.lite.Interpreter(model_path=str(TFLITE_PATH))
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    scale, zero_point = inp["quantization"]

    cases = []
    for case_id, row in enumerate(chosen.itertuples(index=False)):
        idx = id_to_idx[int(row.sample_id)]
        x = X[idx]  # (32,32,2) float32 in {0,1}
        q = np.round(x / scale + zero_point)
        q = np.clip(q, -128, 127).astype(np.int8)
        flat = q.reshape(-1)  # C-order flatten, NHWC
        cases.append({
            "case_id": case_id,
            "sample_id": int(row.sample_id),
            "lot_id": row.lot_id,
            "class_name": row.class_name,
            "class_idx": int(row.class_idx),
            "input_bytes_hex": flat.view(np.uint8).tobytes().hex(),
        })

    manifest_path = RESULTS / "comparison_manifest.json"
    with manifest_path.open("w") as f:
        json.dump({
            "model_tag": CHOSEN_TAG,
            "model_path": str(TFLITE_PATH.relative_to(ROOT)),
            "input_scale": float(scale),
            "input_zero_point": int(zero_point),
            "n_cases": len(cases),
            "cases": cases,
        }, f, indent=2)
    print("Wrote", manifest_path)

    # C header: one flat array of 20 * 2048 int8 inputs + a small per-case
    # table (case_id already implies index; class label is NOT embedded,
    # since the firmware/DUT must not receive ground truth).
    header_lines = [
        "// Generated by ml/select_comparison_cases.py. Do not edit by hand.",
        "// 20 deterministic test-split comparison cases (prompt Section 7).",
        "// Ground-truth labels are intentionally NOT included here.",
        "#ifndef WAFER_COMPARISON_INPUTS_H",
        "#define WAFER_COMPARISON_INPUTS_H",
        "#include <stdint.h>",
        "#define N_COMPARISON_CASES 20",
        "#define INPUT_BYTES_PER_CASE 2048",
        "static const int8_t comparison_inputs[N_COMPARISON_CASES][INPUT_BYTES_PER_CASE] = {",
    ]
    for c in cases:
        raw = bytes.fromhex(c["input_bytes_hex"])
        vals = ", ".join(str(np.int8(b)) for b in raw)
        header_lines.append(f"  {{ {vals} }}, // case {c['case_id']} sample_id={c['sample_id']}")
    header_lines.append("};")
    header_lines.append("#endif")
    header_path = SW_GEN / "comparison_inputs.h"
    header_path.write_text("\n".join(header_lines) + "\n")
    print("Wrote", header_path)


if __name__ == "__main__":
    main()
